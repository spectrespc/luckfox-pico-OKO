#!/usr/bin/env bash
# Install the host packages required to build the OKO firmware natively.
#
# The list mirrors the former SDK build container (Ubuntu 22.04) with the
# Debian 13 (trixie) package names:
#   - libtinfo/ncurses 5 -> ncurses 6 (libncurses-dev)
#   - u-boot-tools adds mkimage/mkenvimage used by the image packaging step
#   - repo/git-lfs stay optional (SDK tree is a plain git checkout)
#
# Usage:
#   tools/native/setup_host.sh            # asks for sudo interactively
#   SUDO_ASKPASS=/path/askpass tools/native/setup_host.sh
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"

PACKAGES=(
    git ssh make gcc gcc-multilib g++-multilib g++ expect
    gawk texinfo libssl-dev bison flex fakeroot cmake unzip gperf autoconf
    device-tree-compiler libncurses-dev pkg-config bc python-is-python3
    passwd openssl file cpio rsync
    python3 python3-pip python3-dev ninja-build
    squashfs-tools mtd-utils e2fsprogs dosfstools mtools xz-utils bzip2
    p7zip-full zip wget curl bash-completion locales
    u-boot-tools zlib1g-dev liblz4-dev
)

if [ "$(id -u)" -eq 0 ]; then
    SUDO=()
elif [ -n "${SUDO_ASKPASS:-}" ]; then
    SUDO=(sudo -A)
else
    SUDO=(sudo)
fi

echo "== host packages (Debian 13 trixie) =="
"${SUDO[@]}" apt-get update
"${SUDO[@]}" apt-get install -y "${PACKAGES[@]}"

# The build only needs an UTF-8 locale: C.UTF-8 is generated by libc on
# Debian and is what tools/native/env.sh exports.
if ! locale -a | grep -qi '^C\.utf-\?8$'; then
    echo "C.UTF-8 locale is not available on this host" >&2
    exit 1
fi

# Vendor cross toolchain is a prebuilt x86_64 binary set; verify it still runs
# on this host (no libtinfo.so.5/libncurses.so.5 requirements).
TC_BIN="$ROOT/tools/linux/toolchain/arm-rockchip830-linux-uclibcgnueabihf/bin"
missing=0
for tool in arm-rockchip830-linux-uclibcgnueabihf-gcc \
            arm-rockchip830-linux-uclibcgnueabihf-as \
            arm-rockchip830-linux-uclibcgnueabihf-ld; do
    if ldd "${TC_BIN}/${tool}" 2>/dev/null | grep -q 'not found'; then
        echo "MISSING shared libraries for $tool:" >&2
        ldd "${TC_BIN}/${tool}" 2>/dev/null | grep 'not found' >&2
        missing=1
    fi
done

# ld is a wrapper script in this toolchain, so run the compiler and assembler
# instead of ldd for the runtime check.
"${TC_BIN}/arm-rockchip830-linux-uclibcgnueabihf-gcc" --version >/dev/null
"${TC_BIN}/arm-rockchip830-linux-uclibcgnueabihf-as" --version >/dev/null
if [ "$missing" -ne 0 ]; then
    echo "cross toolchain cannot start on this host" >&2
    exit 1
fi

echo "== done =="
echo "source tools/native/env.sh   # before ./build.sh"